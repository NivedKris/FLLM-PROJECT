"""Collect every finished result into results/REPORT.md (safe to run at any time).

  python scripts/report.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from common.data import ROOT  # noqa: E402

R = ROOT / "results"


def pct(x):
    return f"{100 * x:.1f}"


def asr_ci(labels_file, n_boot=1000, seed=0):
    """95% bootstrap CI of ASR per setting (resampling cases)."""
    import collections
    import random
    by = collections.defaultdict(list)
    for line in open(labels_file):
        r = json.loads(line)
        by[r["setting"]].append(r["label"] == "Success")
    rng = random.Random(seed)
    out = {}
    for st, xs in by.items():
        n = len(xs)
        boots = sorted(sum(xs[rng.randrange(n)] for _ in range(n)) / n for _ in range(n_boot))
        out[st] = (boots[int(0.025 * n_boot)], boots[int(0.975 * n_boot) - 1])
    return out


def main():
    out = ["# Results (auto-generated by scripts/report.py)\n"]

    # retrieval-only
    for f in sorted((R / "retrieval").glob("*.json")):
        d = json.loads(f.read_text())
        out.append(f"## Retrieval only ({d['embedder']})\n")
        out.append("| k | clean recall (tool) | clean recall (server) |\n|---|---|---|")
        for k, v in d["clean"].items():
            out.append(f"| {k} | {pct(v['tool'])} | {pct(v['server'])} |")
        out.append("\n| setting | k | poison retrieved % | poison + target retrieved % |\n|---|---|---|---|")
        for a in d["attack"]:
            out.append(f"| {a['setting']} | {a['k']} | {pct(a['poison_retrieved'])} | {pct(a['co_retrieved'])} |")
        out.append("")

    # clean accuracy (Step 1)
    for f in sorted((R / "clean").glob("*/summary.json")):
        out.append(f"## Clean tool selection: `{f.parent.name}`\n")
        out.append("| setting | n | accuracy % | gold in prompt % | acc given gold in % | avg tools | prompt tokens | completion tokens |")
        out.append("|---|---|---|---|---|---|---|---|")
        for t in json.loads(f.read_text()):
            out.append(f"| {t['setting']} | {t['n']} | {pct(t['accuracy'])} | {pct(t['gold_in_prompt'])} | "
                       f"{pct(t['acc_given_gold_in'])} | {t['avg_tools']:.1f} | {t['avg_prompt_tokens']:.0f} | "
                       f"{t['avg_completion_tokens']:.0f} |")
        out.append("")

    # attacks (Steps 2-4)
    for f in sorted((R / "attack").glob("*/summary.json")):
        if "0.6b" in f.parent.name or f.parent.name.endswith("+smoke"):
            continue
        out.append(f"## Attack: `{f.parent.name}`\n")
        ci = asr_ci(f.parent / "labels.jsonl") if (f.parent / "labels.jsonl").exists() else {}
        out.append("| setting | poison in prompt % | ASR % [95% CI] | ASR given poison in % | direct exec % | tools removed | prompt tokens | ASR T1 / T2 / T3 % |")
        out.append("|---|---|---|---|---|---|---|---|")
        for t in json.loads(f.read_text()):
            lo, hi = ci.get(t["setting"], (float("nan"), float("nan")))
            bp = " / ".join(pct(v) for v in t["ASR_by_paradigm"].values())
            out.append(f"| {t['setting']} | {pct(t['poison_in_prompt'])} | {pct(t['ASR'])} [{pct(lo)}, {pct(hi)}] | "
                       f"{pct(t['ASR_given_poison_in_prompt'])} | {pct(t['direct_exec'])} | "
                       f"{t.get('tools_removed_by_defense', 0):.2f} | {t['avg_prompt_tokens']:.0f} | {bp} |")
        out.append("")

    # defense filter
    f = R / "defense" / "filter_eval.json"
    if f.exists():
        d = json.loads(f.read_text())
        sets = [k[len("detect_"):] for k in next(iter(d.values())) if k.startswith("detect_") and not k.endswith("paradigm")]
        out.append("## Defense filter (no LLM)\n")
        out.append("| filter | clean tools flagged % | " + " | ".join(f"poison detected ({s}) %" for s in sets) + " |")
        out.append("|---|---|" + "---|" * len(sets))
        for name, row in d.items():
            out.append(f"| {name} | {pct(row['clean_fp'])} | " + " | ".join(pct(row[f'detect_{s}']) for s in sets) + " |")
        out.append("")

    (R / "REPORT.md").write_text("\n".join(out))
    print(f"wrote {R / 'REPORT.md'}")


if __name__ == "__main__":
    main()
